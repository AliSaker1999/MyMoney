// Expo config plugin: keep all app data out of Android Auto Backup (cloud)
// and device-to-device transfer.
//
// allowBackup=false alone does NOT stop device-to-device transfer on Android 12+,
// so we also set dataExtractionRules (API 31+) and fullBackupContent (API <= 30),
// excluding every domain.
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');

const BACKUP_RULES = 'mymoney_backup_rules';
const EXTRACTION_RULES = 'mymoney_data_extraction_rules';

const APP_DOMAINS = ['root', 'file', 'database', 'sharedpref', 'external'];
const DEVICE_DOMAINS = ['device_root', 'device_file', 'device_database', 'device_sharedpref'];

const excludeAll = (domains) =>
  domains.map((d) => `    <exclude domain="${d}" path="." />`).join('\n');

const backupRulesXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAndroidPrivacy.js: nothing is backed up (API <= 30). -->
<full-backup-content>
${excludeAll(APP_DOMAINS)}
</full-backup-content>
`;

const extractionRulesXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAndroidPrivacy.js: nothing leaves the device (API >= 31). -->
<data-extraction-rules>
  <cloud-backup>
${excludeAll([...APP_DOMAINS, ...DEVICE_DOMAINS])}
  </cloud-backup>
  <device-transfer>
${excludeAll([...APP_DOMAINS, ...DEVICE_DOMAINS])}
  </device-transfer>
</data-extraction-rules>
`;

function withPrivacyManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:allowBackup'] = 'false';
    app.$['android:fullBackupContent'] = `@xml/${BACKUP_RULES}`;
    app.$['android:dataExtractionRules'] = `@xml/${EXTRACTION_RULES}`;
    delete app.$['android:usesCleartextTraffic'];
    return cfg;
  });
}

function withPrivacyResources(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const xmlDir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, `${BACKUP_RULES}.xml`), backupRulesXml);
      fs.writeFileSync(path.join(xmlDir, `${EXTRACTION_RULES}.xml`), extractionRulesXml);
      return cfg;
    },
  ]);
}

module.exports = function withAndroidPrivacy(config) {
  return withPrivacyResources(withPrivacyManifest(config));
};
